#!/bin/sh
###############################################################################
# 盯 90 秒：每 3 秒记录一次 1 分钟负载 + 当前 CPU 占用最高的进程
#
# 说明：busybox top 的 %CPU 是「进程生命周期平均值」，
#       所以对短命进程反而会显示很高的值 —— 正好用来抓周期性冒出来的耗 CPU 进程
###############################################################################
echo "时刻      1分负载   最高占用进程"
i=0
while [ $i -lt 30 ]; do
    ld=$(cut -d' ' -f1 /proc/loadavg)
    top1=$(top -bn1 2>/dev/null | tail -n +4 |
        awk 'NF>=7 {gsub(/%/,"",$7); if ($7+0 > m) {m=$7+0; name=$8}} END{print m"%"name}')
    mark=""
    case "$ld" in
        2.*|3.*|4.*|5.*|6.*|7.*|8.*|9.*) mark="  <<< 峰值" ;;
    esac
    echo "$(date +%H:%M:%S)   $ld     ${top1:-无}${mark}"
    i=$((i + 1))
    sleep 3
done
